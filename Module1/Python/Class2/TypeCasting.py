# INT -> STR 

salary = 10000
print("Salary Data Type" ,type(salary))
salary = str(salary);
print("Salary Data Type" ,type(salary))

# INT -> BOOL

salary = 2500
print(salary);
print("Salary To BOOL " ,type(salary));
salary = bool(salary);
print("Salary To BOOL " ,type(salary));


